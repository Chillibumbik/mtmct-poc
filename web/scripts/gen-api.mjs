// Generates src/api/types.gen.ts with one named export per API model.
// Prefers web/openapi.json (openapi-typescript); models that never appear in OpenAPI
// (SSE payloads such as JobEvent) are added from the pydantic contract. Without
// openapi.json everything comes from scripts/gen_types.py (json-schema-to-typescript).
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(web, 'src/api/types.gen.ts')
const openapiPath = resolve(web, 'openapi.json')
const isRequest = (name) => /(Create|In|-Input)$/.test(name)

// Responses always carry every field; mark them required so the UI needs no `?.` noise.
function requireAll(defs) {
  for (const [name, schema] of Object.entries(defs)) {
    if (!isRequest(name) && schema.properties) schema.required = Object.keys(schema.properties)
  }
}

async function fromOpenapi() {
  const { default: openapiTS, astToString } = await import('openapi-typescript')
  const spec = JSON.parse(readFileSync(openapiPath, 'utf8'))
  const schemas = spec.components?.schemas ?? {}
  requireAll(schemas)
  const body = astToString(await openapiTS(spec))
  const aliases = Object.keys(schemas)
    .filter((n) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(n))
    .map((n) => `export type ${n} = components['schemas']['${n}']`)
  const missing = await fromPydantic((name) => !(name in schemas))
  return `${body}\n${aliases.join('\n')}\n\n// Not in OpenAPI (SSE payloads), from mtmct.api.schemas:\n${missing}`
}

function normalise(node) {
  if (Array.isArray(node)) return node.forEach(normalise)
  if (!node || typeof node !== 'object') return
  // json-schema-to-typescript understands draft-07 tuples, not 2020-12 `prefixItems`.
  if (node.prefixItems) {
    node.items = node.prefixItems
    delete node.prefixItems
  }
  if (node.properties) {
    for (const p of Object.values(node.properties)) {
      delete p.title
      delete p.default
    }
  }
  Object.values(node).forEach(normalise)
}

function pydanticSchema() {
  const json = execFileSync('uv', ['run', 'python', 'web/scripts/gen_types.py'], {
    cwd: resolve(web, '..'),
    encoding: 'utf8',
  })
  return JSON.parse(json)
}

/** json2ts over the pydantic contract; `include` limits the emitted root models (and what they reference). */
async function fromPydantic(include = () => true) {
  const { compile } = await import('json-schema-to-typescript')
  const schema = pydanticSchema()
  schema.properties = Object.fromEntries(Object.entries(schema.properties).filter(([name]) => include(name)))
  if (Object.keys(schema.properties).length === 0) return ''
  requireAll(schema.$defs)
  normalise(schema)
  const ts = await compile(schema, 'ApiSchemas', { bannerComment: '', additionalProperties: false, format: false })
  // The synthetic root interface only exists to make every model reachable.
  return ts.replace(/^export interface ApiSchemas \{[\s\S]*?^\}\n/m, '')
}

const source = existsSync(openapiPath) ? 'openapi.json' : 'mtmct.api.schemas'
const body = source === 'openapi.json' ? await fromOpenapi() : await fromPydantic()
writeFileSync(out, `/* eslint-disable */\n// AUTO-GENERATED by \`pnpm gen:api\` from ${source}. Do not edit.\n\n${body}`)
console.log(`wrote ${out} from ${source}`)
